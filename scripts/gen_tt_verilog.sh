#!/usr/bin/env bash
# Flatten SystemVerilog → a single Yosys-readable Verilog file for Tiny Tapeout.
#
# TT's LibreLane path uses Yosys's limited SV frontend, which rejects packages
# with `return`, `import pkg::*`, unpacked array ports, etc. Cocotb keeps using
# the original .sv sources via test/filelist.f; info.yaml points at the bundle.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/src/tt_bundle.v"
FILELIST="$ROOT/test/filelist.f"

if ! command -v sv2v >/dev/null 2>&1; then
  echo "error: sv2v not found on PATH" >&2
  echo "  macOS:  brew install sv2v" >&2
  echo "  other:  https://github.com/zachjs/sv2v/releases" >&2
  exit 1
fi

TMPDIR_SV2V="$(mktemp -d "${TMPDIR:-/tmp}/kraken_tt.XXXXXX")"
TMP="$TMPDIR_SV2V/bundle.v"
trap 'rm -rf "$TMPDIR_SV2V"' EXIT

# shellcheck disable=SC2046
set -- $(awk '!/^[[:space:]]*#/ && NF {print}' "$FILELIST")
if [[ $# -eq 0 ]]; then
  echo "error: no sources in $FILELIST" >&2
  exit 1
fi

(
  cd "$ROOT"
  sv2v --write="$TMP" "$@"
)

{
  echo "// Generated by scripts/gen_tt_verilog.sh — do not edit."
  echo "// Source of truth: src/*.sv listed in test/filelist.f"
  echo "// Regenerated for Tiny Tapeout / Yosys (packages, import, return, ...)."
  echo ""
  cat "$TMP"
} > "$OUT"

echo "wrote $OUT ($(wc -l < "$OUT") lines)"
